# ---------------- 1. 知识主体识别 + 指代消解 ----------------
# 调用方：item_name_confirm_node，占位符 history_text / query
ITEM_NAME_EXTRACT_TEMPLATE = """
历史会话：
{history_text}

当前用户问题：{query}

请根据历史会话和当前问题，判断用户正在询问的【知识主体】。
知识主体指生物对象，可能是：物种、基因、蛋白、通路、疾病、组织/细胞系、实验方法、试剂。
1. 如果用户明确提到了主体名称，请原样提取（保持规范写法，如 TP53、CRISPR-Cas9）。
2. 如果用户使用了代词（如"它""这个""该方法"），请结合历史会话做指代消解，确定主体。
3. 如果无法确定主体，item_names 返回空列表。
4. 请把用户问题改写成不依赖上下文、可独立检索的完整问题（rewritten_query），
   改写时补全主体名称，但不要凭空添加用户没问的内容。

请直接返回 JSON 格式结果，格式如下：
{{
    "item_names": ["知识主体A", "知识主体B"],
    "rewritten_query": "关于知识主体A和知识主体B，..."
}}"""


# ---------------- 2. HyDE：先写一段"假想文献片段"再检索 ----------------
# 调用方：hyde_search_node，占位符 item_hint / rewritten_query
USER_HYDE_PROMPT_TEMPLATE = """请模拟一段生物医学文献或实验方案中的内容，该内容能够回答以下用户问题。

相关知识主体：
{item_hint}

用户问题：
{rewritten_query}

要求：
1. 以科研论文、综述或实验方法学的口吻撰写，使用陈述句
2. 直接描述机制、实验结果或操作要点，不要出现"假设""可能""大概"等不确定用语
3. 包含具体的基因名、蛋白名、通路名、试剂名、实验条件等关键词，保持与问题高度相关
4. 不需要标题和格式标记，只输出正文段落
5. 使用中文（专业名词保留英文原文），300-350字
"""


# ---------------- 3. 图谱实体抽取 ----------------
# 调用方：kg_search_node，占位符 MAX_ENTITY_NAME_LENGTH
ENTITY_EXTRACT_SYSTEM_PROMPT = """
你是一个生物医学知识图谱问答系统的"实体识别"领域专家。
请从用户问题中抽取用于查询图数据库(Neo4j)的实体名称。

【约束】
1) 优先抽取这些类型的名词短语：物种、基因、蛋白、通路、疾病、组织/细胞系、实验方法、试剂、实验条件
2) 每个实体名称不超过 {MAX_ENTITY_NAME_LENGTH} 个字符，超过请截取核心部分，实体名不要重复
3) 不要输出完整句子，也不要把"如何""是什么"这类疑问词当作实体，只输出实体关键词
4) 基因名/蛋白名保持文献中的规范写法（如 TP53、Cas9），不要意译
5) 输出必须是严格 JSON，只含一个字段 entities（字符串数组）
6) 请严格遵循提示词要求，如果违背，你将受到严重的惩罚，甚至导致系统的崩溃。

【输出示例】
{{"entities": ["TP53", "细胞凋亡", "HeLa 细胞"]}}
"""


